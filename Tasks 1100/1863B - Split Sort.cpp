#include <iostream>
#include <vector>
#include <map>
using namespace std;

int main()
{
    // Суть задачи можно поэтопано разобрать во первых что будет когда мы выберем 'x'
    // нам нужно получить отсортированную последовательность если когда мы выбираем 'x' какое-то число
    // которое было меньше 'x' но при этом стояло раньше числа которое меньше его тогда это число
    // испортит отсортированность что значит нам нужно выбирать только те 'x' до которых не включительно
    // все числа идут строго в правильном порядке это остановится на числе правый сосед которого был
    // ранее и ровно этому соседу равен нынешний 'x' но что отличает это число остановщик последовательностей от
    // прочих чисел его отличие в том что его правый сосед то есть просто на один более его стоит раньше его 
    // и когда до этого числа дойдут его сосед стоит неправильно он испортит опследовательность 
    // Из этого следует что порча последовательности прибавлет действия и портят её числа остановщики
    // а чтобы посчиать остновщики нужны просто посчитать у скольких чисел последующее число то есть +1
    // стоит раньше его самого
    ios::sync_with_stdio(false);
    cin.tie(NULL);
    int t;
    cin >> t;
    while (t--) {
        int n;
        cin >> n;
        vector<int> a(n);
        for (int& c : a)cin >> c;
        vector<bool> pos(n+67,0);
        int cou = 0;
        for (int c : a) {
            if (pos[c + 1]) {
                cou++;
            }
            pos[c] = 1;
        }
        cout << cou << "\n";
    }
}


