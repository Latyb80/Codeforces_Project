#include <iostream>
#include <vector>
using namespace std;

using ll = long long;

int main()
{
    // Суть задачи строится на модульной арифметике и теории чисел сама концепция
    // решения получается простой но выглядит как пальцем в небо 
    // Решение заключается в нахождении опорного делителя как мы занем база модульной
    // остаток суммы чисел по модулю равен сумме их остатков какое число нужно прибавлять
    // чтобы можно было всегда довести остаток до модуля и обнулить его ответ это 1 он всегда
    // может довести любое число до кратности значит нам нужно число которое на нашему опорному
    // модулю будет 1 тогда перевернём взгляд и пойдём от числа второго допустим наша однёрка это
    // k которое нам подают тогда чтобы он стал единицей нужно делить его на k-1 вот и наш мнимый делитель
    // мы можем сделать k операций то есть прибавить 1 к остатку k раз при этом как много в худшем случае
    // нам нужно довести остаток если он 1 до k-1 ответ k-2 при этом у нас есть k единиц чего хватает с лихвой
    // Есть 2 исключения k == 1 , 2 в этих случаях если k == 1 задача тривиальна просто доводим все числа до
    // чётных а вот если k == 2 то тут сложнее возьмём мнимый делитель 3 у него 2 остатка 1 и 2 до тройки
    // им не хвтает 2 и 1 соответственно а когда k == 2 мы можем прибавить или 2 или 4 что mod 3 = 2 и 1
    // мы можем довести любое число до кратности так как имеем все варианта дефицита остатков
    //
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int t;
    cin >> t;
    while (t--) {
        ll n, k;
        cin >> n >> k;
        vector<ll> a(n);
        ll modi = k - 1;
        for (ll& c : a)cin >> c;
        if (k == 1) {
            for (ll c : a)cout << c + c % 2 << " ";
            cout << "\n";
            continue;
        }
        if (k == 2) {
            for (ll c : a)cout << c + c % 3 * 2 << " ";
            cout << "\n";
            continue;
        }
        for (ll& c : a) {
            cout << c + (modi - c % modi) % modi * k << " ";
        }
        cout << "\n";
    }
}


