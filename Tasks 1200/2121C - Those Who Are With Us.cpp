#include <iostream>
#include <vector>
#include <algorithm>
#define mel max_element
using namespace std;

using vv = vector<int>;

int main()
{
    //  Суть задачи длинная поэтому описание будет поэтапным первое что можно
    // выделить для простоты это то что мы просто выбираем какую-то строку и столбик 
    // это простым языком их формальное уравнение а также стоит сказать что в условии не написано
    // а именно там не говорится о том что в месте пересечения мы не делаем -2 за строку и столбик
    // а просто -1 это доказыают примеры иллюстрированные также мы должны понизить максимум при этом
    // у нас получается всего 2 вариант ответа мы не смогли понизить все максимумы и в ответ просто начлаьный
    // максимум пойдёт и второй мы смогли понизить все максимумы тогда в отве максимум - 1 больше понизить мы 
    // не можем никак 
    // Дальше уже сложнее мы находим самый выгодный столбик где больше всего максимумов а если его нету то есть максимумов
    // несколько мы уходим на строки и выбираем из них если же и там несколько максимумов то мы никак не можем
    // убрать все максимумы так как одна строка и столбик никак не закроют более одного сразу выводим начальный максимум
    // Если же мы смогли выбрать строку или столбик то все максимумы на выбранной оси убираем после чего
    // проверяем второй то есть после столбиков проверяем строки и наоборот если во втором оказалось более
    // одного элемента у которого остались максимумы тогда это невозможно иначе выводим максимум - 1 
    // Варинты типа n == 1 или максимумов менее 3 или m == 1 сразу отметаем там гарантированно максимум - 1
    //
    ios::sync_with_stdio(false);
    cin.tie(NULL);
    int q;
    cin >> q;
    while (q--) {
        int n, m;
        cin >> n >> m;
        vector<vv> a(n, vv(m));
        vv str(n,0);
        vv tow(m,0);
        int lord = 0,cou = 1;
        for (vv& c : a)for (int& b : c) {
            cin >> b; 
            if (b > lord)lord = b, cou = 1;
            else if (b == lord)cou++;
        }
        if (n == 1 || m == 1 || cou < 3) {cout << lord - 1 << "\n"; continue;}
        for (int i = 0; i < n; i++) {
            for(int j = 0; j < m; j++){
                if (a[i][j] == lord)tow[j]++, str[i]++;
            }
        }
        auto s = str.begin(), s1 = str.end();
        auto t = tow.begin(), t1 = tow.end();
        if (count(s, s1, *mel(s, s1)) > 1) {
            if (count(t, t1, *mel(t, t1)) > 1) { cout << lord << "\n"; continue; }
            int idx = mel(t, t1) - t;
            for (int i = 0; i < n; i++) {
                if (a[i][idx] == lord)str[i]--;
            }
            if (count_if(s, s1, [](int a) {return a > 0; }) > 1)cout << lord << "\n";
            else cout << lord - 1 << "\n";
        }
        else{
            if (count(s, s1, *mel(s, s1)) > 1) { cout << lord << "\n"; continue; }
            int idx = mel(s, s1) - s;
            for (int j = 0; j < m; j++) {
                if (a[idx][j] == lord)tow[j]--;
            }
            if (count_if(t, t1, [](int a) {return a > 0; }) > 1)cout << lord << "\n";
            else cout << lord - 1 << "\n";
        }

    }
}

