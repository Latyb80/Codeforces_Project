#include <iostream>
#include <vector>
#include <algorithm>
#define s second
#define f first
using namespace std;

using pii = pair<int, int>;

int main()
{
    // В данной задаче нужно быть внимательным к условиям а именно выигрыш(real) в казино не будет менее
    // его нижней границы при этом если мы уже выше верхней то смысла от выигрыша нету он гарантированно
    // проигрышный для нас тогда идём от нижайших границ до высочайших попутно собирая выгодные выигрыши
    // следовательно верхняя граница не имеет смысла вообще ведь нам никогда не придётся спускаться вниз
    // по выигрышам это не релеватно 
    // Когда мы идём по массиву обновляя максимум мы гарантируем что максимальный вариант на каждом шаге
    // и чем выше нижняя граница тем выше выигрыш то есть мы также гарантируем что выше по границе всегда
    // выгоднее и что мы можем фактически взять любой выигрыш по нижней границе которого проходим 
    // поэтому мы также можем взять и максимальный выигрыш
    //
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int t;
    cin >> t;
    while (t--) {
        int n,musor,k;
        cin >> n >> k;
        vector<pii> a(n);
        for (pii& c : a)cin >> c.f >> musor >> c.s;
        sort(a.begin(), a.end(), [](pii y, pii z) {return y.f < z.f; });
        int nmax = k;
        for (pii c : a)
            if (nmax < c.f)break;
            else nmax = max(nmax, c.s);
        cout << nmax << "\n";
    }
}


