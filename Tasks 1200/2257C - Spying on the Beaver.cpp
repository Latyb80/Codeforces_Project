#include <iostream>
#include <vector>
using namespace std;

int main()
{
    // Суть заключается в том что это древовидный граф то есть не циклинчый и бобр не может
    // пройти через плотину дважды проще говря бобр всегда идёт вперёд и у нас есть 2 сложности того
    // как понять где бобр первая это на развилках когда у бобра несколько выборов пути при это именно
    // пути где есть плотина прочие не важны а также проблема это проверить когда в одном звене более
    // одной плотины за каждой плотиной кроме последней тоже камера чтобы проверить не остановился ли бобр
    // на этом шагу 
    // Чтобы это сделать мы идём от плотин и поднимаемся вплоть до 1 и по пути все числа помечаем они
    // имеют смысл тк ведут к плотине когда мы пересекаемся с уже помеченой вершиной мы прибавляем +1 к счёту
    // камер тк здесь уже как минимум 2 вариант это или разветвление или это следующая плотина и если первый очевиден
    // то за второе плюсуем изза того что это значит что плотина уже не последняя и за неё нужно ставить камеру и в первом 
    // и во втором случаях мы выходим с линии этой плотины и идём также по следующей
    //
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int t;
    cin >> t;
    while (t--) {
        int n,cou = 0;
        cin >> n;
        vector<int> p(n + 7);
        for (int i = 2; i <= n; i++) {
            cin >> p[i];
        }
        int m;
        cin >> m;
        vector<bool> che(n + 7);
        vector<int> plot(m);
        vector<int> ans;
        for (int& c : plot)cin >> c, che[c] = true;
        for (int c : plot) {
            if (c == 1)continue;
            int lx = c;
            int x = p[c];
            while (x != 0) {
                if (che[x]) {
                    ans.push_back(lx);
                    cou++;
                    break;
                }
                che[x] = true;
                lx = x;
                x = p[x];
            }
        }
        cout << ans.size() << " ";
        for (int c : ans)cout << c << " ";
        cout << "\n";
    }
}

