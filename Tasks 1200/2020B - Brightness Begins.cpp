#include <iostream>
#include <cmath>
#include <algorithm>
using namespace std;

using ll = long long;
ll f(const ll n) {
    ll sq = sqrtl(n);
    while (sq * sq > n) sq--;
    while ((sq + 1) * (sq + 1) <= n) sq++;
    return n - sq;
}
int main()
{
    // Задача строится на концепциях бинпоиска и его модификацию
    // Главная суть это то как подсчитать делители то включится лампочка или нет
    // зависит от чётности количества её делителей это самое базово свойство задачи
    // Второе чтобы подсчитать вспоминаем метод подсчёта делителей до корня квадратного
    // и у каждого делителя есть пара кроме исключения это совершенные квадрат у их корня
    // нету пары различной от него поэтому он имеет нечётное кол-во делитеелей и такая лампочка погаснет
    // Ещё просто свойство это то что количество подобных корней до n равно корню квадратному из n(окгругление вниз)
    // включительно то есть формула расчёт работающиз из n лампочек n - sqrtl(n) где sqrtl округлённый корень числа n вниз
    // Второе бинпоиск функция монотонно возрастает то есть чем больше n тем больше ламп но выключенных не так много
    // значит используем бинпоиск с модификацией если находим ответ то идём дальше ведь он не априори минимален 
    // и идём когда нашли ответ строго вниз ведь все ответы вверх будут всегда более найденного 
    // В прочем это базовый бинпоиск 
    // Стоит подметить большие цифры и использование специфичных для малых чисел проверок
    //
    ios::sync_with_stdio(false);
    cin.tie(NULL);
    int t;
    cin >> t;
    while (t--) {
        ll k;
        cin >> k;
        ll L = 1, R = 2e18, mid;
        ll ans = 2e18;
        while (L <= R) {
            mid = L + (R - L) / 2;
            if (f(mid) > k)R = mid - 1;
            else if (f(mid) < k)L = mid + 1;
            else ans = min(ans, mid), R = mid - 1;
        }
        cout << ans << "\n";
    }
}


