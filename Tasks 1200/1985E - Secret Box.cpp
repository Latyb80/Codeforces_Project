#include <iostream>
using namespace std;

using ll = long long;
ll x, y, z, k;
long long check(ll x1, ll y1, ll z1);

int main()
{
    // Первое что нужно это проверить все варианты того как можно собрать k из трёх сторон
    // это не математика так что разложить на простые не вариант поэтому тут логика это мод на подсчёт 
    // делителей через корень квадратный она заключается в том чтобы перебрать двумя цикламии все УНИКАЛЬНЫЕ
    // тройки сторон внешний идёт до корня кубичесого это максимум второй до корня квадратного по частному 
    // внутри второго цикла проверяем тройки так как там проверяются только уникалальные а по правилам мы можем
    // поворачивать наш брус на 90 градусов(параллельность не теряется) то есть просто перебираем все возможны комбиации
    // этих 3 цифр и ставим их на все возможные места и находим самый многовариантный как подсчиать ниже
    // Чтобы подсчитать варианты нужно посчитать то сколько положений у бруса по всем координатам и перемножить
    // обьянсяется базовой комбинаторикой также важно + 1 это начальная позиция отсчёта и разность
    // внешенго бруса и нашего +1 это и есть его позиции и так по всем координатам так у нас есть вариант на каждую сторону
    // они независимы следовательно перемножаются для подсчёта
    //
    ios::sync_with_stdio(false);
    cin.tie(NULL);
    int t;
    cin >> t;
    while (t--) { 
        cin >> x >> y >> z >> k;
        ll fir;
        ll maxv = 0;
        for (ll i = 1; i * i * i <= k; i++) {
            if (k % i != 0)continue;
            fir = k / i;
            for (ll j = 1; j * j <= fir; j++) {
                if (fir % j != 0)continue;
                ll c = fir / j;
                maxv = max(maxv, check(i, j, c));
                maxv = max(maxv, check(i, c, j));
                maxv = max(maxv, check(j, i, c));
                maxv = max(maxv, check(j, c, i));
                maxv = max(maxv, check(c, i, j));
                maxv = max(maxv, check(c, j, i));     
            }
         }
        cout << maxv << '\n';
    }
}
long long check(ll x1, ll y1, ll z1) {
    if (x1 <= x && y1 <= y && z1 <= z) {
        ll h = (x - x1 + 1) * (y - y1 + 1) * (z - z1 + 1);
        return h;
    }
    else return 0;
}

