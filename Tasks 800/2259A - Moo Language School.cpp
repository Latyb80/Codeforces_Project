#include <iostream>
using namespace std;

int main()
{
    // Если всю эту тонну лирики убрать то нас просят чтобы в каждой ферме
    // была школа Му тогда нам нужно чтобы была хотя бы одна земля у фермера Джона
    // то есть на каждой ферме хотя бы один 0 ферма это k последовательных полей значит
    // нужно чтобы каждые k символов был хотя бы 1 ноль иначе +1 к платным постройкам
    int t;
    cin >> t;
    while (t--) {
        int n, k, cou = 0;
        cin >> n >> k;
        bool ok = 0;
        for (int i = 0; i < n/k; i++) {
            ok = 0;
            for (int j = 0; j < k; j++) {
                char c;
                cin >> c;
                if (c == '0')ok = 1;
            }
            if (!ok)cou++;
        }
        cout << cou << "\n";
    }
}


