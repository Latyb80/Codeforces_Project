#include <iostream>
using namespace std;

int main()
{
    // Логика заключается в том что мы можем забирать слево книги и тащить их вправо
    // и мы обязаны оставить книг столько чтобы поддреживать минимальную последоватлеьность
    // то есть 1 2 3 и тд и если у кого-то числа более число нежели его индекс то просто забираем 
    // его и также если недостаток то мы отдаём если на каком-то моменте сумма станет отрицательной
    // то есть нам не хватило отдать значит это невозможно
    //
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int t;
    cin >> t;
    while (t--) {
        int n;
        cin >> n;
        bool ans = 1;
        long long sum = 0, cou = 1;
        while (n--) {
            long long b;
            cin >> b;
            sum += b-cou;
            if (sum < 0)ans = 0;
            cou++;
        }
        cout << ((ans) ? "YES\n" : "NO\n");
    }
}

